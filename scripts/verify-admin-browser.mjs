import { chromium } from 'playwright';
import { createClient } from '@supabase/supabase-js';
import { readFile } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import assert from 'node:assert/strict';
const token=process.env.SUPABASE_ACCESS_TOKEN,ref=process.env.SUPABASE_PROJECT_REF;
if(!token||!ref)throw new Error('Faltan las variables privadas de administración.');
const response=await fetch(`https://api.supabase.com/v1/projects/${ref}/api-keys`,{headers:{Authorization:`Bearer ${token}`}});
if(!response.ok)throw new Error(`Management HTTP ${response.status}`);
const keys=await response.json();
const service=createClient(`https://${ref}.supabase.co`,keys.find(k=>k.name==='service_role').api_key,{auth:{persistSession:false}});
const access=await readFile('.local/ACCESO-ADMIN.txt','utf8');
const email=access.match(/^Correo: (.+)$/m)[1],password=access.match(/^Contraseña inicial: (.+)$/m)[1];
const sku='UI-CHECK-'+randomUUID(),name='Artículo temporal de verificación';
const browser=await chromium.launch();let imagePath;
const page=await browser.newPage({viewport:{width:1440,height:1000}});
try{
 await page.goto('http://127.0.0.1:5173/cuenta');
 await page.getByLabel('Correo electrónico').fill(email);
 await page.getByLabel('Contraseña',{exact:true}).fill(password);
 await page.getByRole('button',{name:'Iniciar sesión',exact:true}).click();
 await page.getByRole('link',{name:'Abrir dashboard'}).click();
 await page.getByRole('button',{name:'Productos',exact:true}).click();
 await page.getByRole('button',{name:'Nuevo producto'}).click();
 await page.getByRole('textbox',{name:'Nombre',exact:true}).fill(name);
 await page.getByLabel('SKU / Referencia').fill(sku);
 await page.getByLabel('Precio RD$').fill('1750');
 await page.getByLabel('Stock',{exact:true}).fill('5');
 await page.getByLabel('Descripción').fill('Prueba de interfaz: se elimina al terminar.');
 await page.locator('input[type="file"]').setInputFiles('public/logo.jpeg');
 await page.waitForFunction(()=>document.querySelector('input[pattern]')?.value?.startsWith('https://'));
 const imageUrl=await page.getByLabel('Imagen (URL https o ruta /)').inputValue();
 imagePath=imageUrl.split('/product-images/')[1];
 await page.getByLabel('Visible en la tienda').uncheck();
 await page.getByRole('button',{name:'Guardar producto'}).click();
 await page.getByRole('button',{name:'Editar '+name}).waitFor();
 await page.getByRole('button',{name:'Editar '+name}).click();
 await page.getByLabel('Precio RD$').fill('1890');
 await page.getByLabel('Stock',{exact:true}).fill('3');
 await page.getByRole('button',{name:'Guardar producto'}).click();
 await page.getByRole('dialog').waitFor({state:'hidden'});
 const {data,error}=await service.from('products').select('price,stock,active,image_url').eq('sku',sku).single();
 if(error)throw error;
 assert.equal(data.price,1890);assert.equal(data.stock,3);assert.equal(data.active,false);assert.ok(data.image_url.startsWith('https://'));
 console.log('PASS navegador real: iniciar sesión, abrir panel, crear artículo, subir foto, editar precio y stock, guardar en Supabase.');
 await page.screenshot({path:'.local/verificacion-admin.png',fullPage:true});
}finally{
 const {error}=await service.from('products').delete().eq('sku',sku);if(error)console.error('No se pudo limpiar el artículo temporal.');
 if(imagePath)await service.storage.from('product-images').remove([imagePath]);
 await browser.close();
}
